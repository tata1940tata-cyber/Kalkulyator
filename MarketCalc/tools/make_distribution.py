# -*- coding: utf-8 -*-
"""Сборка папки и zip-архива с дистрибутивом МАРКЕТ."""

import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DIST = ROOT / "МАРКЕТ_дистрибутив"
ZIP = ROOT / "МАРКЕТ_дистрибутив.zip"

TEXT = """МАРКЕТ — калькулятор юнит-экономики Яндекс Маркета
====================================================

УСТАНОВКА (в один клик)
1. Двойной клик по файлу «МАРКЕТ_Установка.exe».
2. Если Windows покажет окно SmartScreen — нажмите «Подробнее» → «Выполнить всё равно».
3. Дальше ничего нажимать не нужно: установка начнётся сама,
   приложение запустится, ярлык «МАРКЕТ» появится на рабочем столе и в меню «Пуск».

Права администратора не требуются.
Папка установки: %LOCALAPPDATA%\\Programs\\MarketCalc

ЧТО В ПАПКЕ
- МАРКЕТ_Установка.exe — установщик приложения
- Шаблон_данных_Маркет.xlsx — пустой шаблон таблицы для загрузки
- доп.товары для загрузки.xlsx — 20 готовых товаров для проверки
- Портативная версия\\MarketCalc.exe — запуск без установки
- README.md — краткая документация

КАК ЗАГРУЗИТЬ СВОИ ДАННЫЕ
1. Откройте приложение и нажмите «Загрузить данные».
2. Выберите файл .xlsx или .csv.
3. Обязательный минимум: наименование и цена. Остальные колонки — по возможности.
   Листы «Комиссии», «Логистика», «Прочие тарифы», «Акции», «Настройки» необязательны.

УДАЛЕНИЕ
Параметры → Приложения → «МАРКЕТ — калькулятор юнит-экономики» → Удалить.
Данные и настройки лежат в %LOCALAPPDATA%\\MarketCalc и при удалении не теряются.

Приложение работает офлайн и не отправляет данные в интернет.
Цены в демонстрационных файлах — примеры, не оферта.
"""

README = """# МАРКЕТ — калькулятор юнит-экономики

## Установка

Двойной клик по **МАРКЕТ_Установка.exe** — установка идёт автоматически, без кнопок.
Приложение ставится для текущего пользователя, права администратора не нужны.

* папка: `%LOCALAPPDATA%\\Programs\\MarketCalc`
* ярлыки: рабочий стол и меню «Пуск»
* если Windows покажет SmartScreen: «Подробнее» → «Выполнить всё равно»

## Что умеет

* маржа и маржинальность по текущей цене;
* цена под целевую маржинальность и ДРР;
* маржа по ценам входа в акции и максимальная допустимая скидка;
* обзор портфеля SKU, тарифы площадки, выгрузка отчёта в Excel.

## Данные

Кнопка «Загрузить данные» принимает `.xlsx` или `.csv`. Минимум — наименование и цена.
Шаблон: `Шаблон_данных_Маркет.xlsx`. Пример: `доп.товары для загрузки.xlsx` (20 SKU, 5 категорий).

## Портативный запуск

`Портативная версия\\MarketCalc.exe` — работает без установки.

## Удаление

«Параметры → Приложения → МАРКЕТ — калькулятор юнит-экономики».
Данные в `%LOCALAPPDATA%\\MarketCalc` сохраняются.
"""


def main():
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)

    shutil.copy2(ROOT / "МАРКЕТ_Установка.exe", DIST / "МАРКЕТ_Установка.exe")
    shutil.copy2(ROOT / "MarketCalc" / "release" / "Шаблон_данных_Маркет.xlsx", DIST / "Шаблон_данных_Маркет.xlsx")
    shutil.copy2(ROOT / "доп.товары для загрузки.xlsx", DIST / "доп.товары для загрузки.xlsx")

    portable = DIST / "Портативная версия"
    portable.mkdir()
    shutil.copy2(ROOT / "MarketCalc" / "release" / "MarketCalc.exe", portable / "MarketCalc.exe")

    (DIST / "ПРОЧТИ_МЕНЯ.txt").write_text(TEXT, encoding="utf-8-sig")
    (DIST / "README.md").write_text(README, encoding="utf-8")

    if ZIP.exists():
        ZIP.unlink()
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in DIST.rglob("*"):
            archive.write(path, path.relative_to(ROOT))

    print("folder:", DIST)
    for path in sorted(DIST.rglob("*")):
        if path.is_file():
            print(f"  {path.relative_to(DIST)}  {path.stat().st_size / 1024 / 1024:.1f} МБ")
    print("zip:", ZIP, f"{ZIP.stat().st_size / 1024 / 1024:.1f} МБ")


if __name__ == "__main__":
    main()
